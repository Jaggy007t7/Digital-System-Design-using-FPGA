module half_adder(input a, b, output s, c);
    assign s = a ^ b;
    assign c = a & b;
endmodule

module full_adder(input a, b, cin, output sum, c);
    assign sum = a ^ b ^ cin;
    assign c = (a&b) | (a&cin) | (b&cin);
endmodule

